#!/usr/bin/env python3
"""Generate the handbook's reference tables from the code.

    sh tools/docs-tables            write book/_generated/
    sh tools/docs-tables --check    fail if book/_generated/ is stale or the
                                    coverage notes disagree with the code

Reads, without running R, Python or Stata:
- r/NAMESPACE (R exports), python/src/__init__.py (__all__), stata/src/*.ado;
- the API dispatch tables in r/R/dw_api.R and python/src/dw_api.py;
- the auditor rule registries in r/R/test_scripts.R and python/src/test_scripts.py;
- conformance/cases/*.json;
- book/_data/coverage.json, the hand-kept row order and notes.

Writes, under book/_generated/ (included by the handbook, never edited by hand):
- functions-<section>.md   the coverage matrix, one table per section;
- badges/<function>.md     a one-line "which languages" note for chapters;
- api-keys.md              the api= keys, per language, with cache format;
- audit-rules.md           the contract auditor's rules, per language;
- parity-cases.md          the parity certificate's cases.

Standard library only (Python 3.8+), like conformance/certify.py.
"""
from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "book" / "_generated"
NOTES = REPO / "book" / "_data" / "coverage.json"
LANGS = ("r", "python", "stata")
LANG_NAME = {"r": "R", "python": "Python", "stata": "Stata"}
HEADER = ("<!-- Generated by book/_scripts/gen_tables.py from the code and "
          "book/_data/coverage.json. Do not edit: run `sh tools/docs-tables`. -->\n")


class NotesError(Exception):
    pass


# --------------------------------------------------------------------------
# reading the code
# --------------------------------------------------------------------------

def _collapse_aliases(names: set) -> set:
    """Drop dw_<x> when <x> is also exported: it is an alias, not a function."""
    return {n for n in names if not (n.startswith("dw_") and n[3:] in names)}


def r_exports() -> set:
    text = (REPO / "r" / "NAMESPACE").read_text(encoding="utf-8")
    return _collapse_aliases(set(re.findall(r"^export\(([^)]+)\)", text, flags=re.M)))


def python_exports() -> set:
    tree = ast.parse((REPO / "python" / "src" / "__init__.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            names = {ast.literal_eval(e) for e in node.value.elts}
            return _collapse_aliases({n for n in names if not n.startswith("_")})
    raise SystemExit("[docs-tables] python/src/__init__.py has no __all__ list.")


def stata_exports() -> set:
    return {p.stem for p in (REPO / "stata" / "src").glob("*.ado") if not p.stem.startswith("_")}


def api_keys() -> dict:
    """{key: {"r": bool, "python": bool, "r_ext": str, "python_ext": str}}"""
    r_src = (REPO / "r" / "R" / "dw_api.R").read_text(encoding="utf-8")
    r_keys = re.findall(r'^\s*"([a-z_]+)"\s*=\s*do\.call\(\.api_fetch_', r_src, flags=re.M)
    m = re.search(r"\.dw_api_default_ext <- function\(api\) \{(.*?)\n\}", r_src, flags=re.S)
    if not m:
        raise SystemExit("[docs-tables] cannot find .dw_api_default_ext in r/R/dw_api.R.")
    r_ext = dict(re.findall(r'"([a-z_]+)"\s*=\s*"([a-z]+)"', m.group(1)))
    r_default = re.findall(r'^\s*"([a-z]+)"\s*$', m.group(1), flags=re.M)
    r_default = r_default[-1] if r_default else "csv"

    py_src = (REPO / "python" / "src" / "dw_api.py").read_text(encoding="utf-8")
    m = re.search(r"^_DISPATCH = \{(.*?)^\}", py_src, flags=re.S | re.M)
    if not m:
        raise SystemExit("[docs-tables] cannot find _DISPATCH in python/src/dw_api.py.")
    py_keys = re.findall(r'^\s*"([a-z_]+)"\s*:', m.group(1), flags=re.M)
    m = re.search(r'def _dw_api_default_ext\(.*?\n(.*?)\n(?=def |\S)', py_src, flags=re.S)
    py_ext_block = m.group(1) if m else ""
    py_other = {}
    for keys, ext in re.findall(r'if api in \(([^)]*)\):\s*\n\s*return "([a-z]+)"', py_ext_block):
        for k in re.findall(r'"([a-z_]+)"', keys):
            py_other[k] = ext
    py_default = (re.findall(r'^\s*return "([a-z]+)"\s*$', py_ext_block, flags=re.M) or ["csv"])[-1]

    out = {}
    for k in list(dict.fromkeys(r_keys + py_keys)):
        out[k] = {
            "r": k in r_keys, "python": k in py_keys,
            "r_ext": r_ext.get(k, r_default), "python_ext": py_other.get(k, py_default),
        }
    return out


def audit_rules() -> dict:
    """{id: {"family": str, "r": msg or None, "python": msg or None}}"""
    rules: dict = {}
    r_src = (REPO / "r" / "R" / "test_scripts.R").read_text(encoding="utf-8")
    for rid, fam, body in re.findall(
            r'list\(id = "([^"]+)",\s*family = "([^"]+)",(.*?)suggest =', r_src, flags=re.S):
        msg = re.search(r'message = "([^"]*)"', body)
        rules.setdefault(rid, {"family": fam, "r": None, "python": None})["r"] = (
            msg.group(1) if msg else "")
    tree = ast.parse((REPO / "python" / "src" / "test_scripts.py").read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and getattr(node.func, "id", None) == "_Rule":
            kw = {k.arg: k.value for k in node.keywords}
            if "id" not in kw:
                continue
            rid = ast.literal_eval(kw["id"])
            fam = ast.literal_eval(kw["family"])
            msg = ast.literal_eval(kw["message"]) if "message" in kw else ""
            rules.setdefault(rid, {"family": fam, "r": None, "python": None})["python"] = msg
    return rules


def cases() -> list:
    out = []
    for p in sorted((REPO / "conformance" / "cases").glob("*.json")):
        c = json.loads(p.read_text(encoding="utf-8"))
        out.append(c)
    return out


# --------------------------------------------------------------------------
# building the tables
# --------------------------------------------------------------------------

def md_escape(s: str) -> str:
    return s.replace("|", "\\|")


def coverage(notes: dict) -> tuple:
    """Return (sections: [(section, rows)], cells: {row_id: {lang: text}}, errors)."""
    have = {"r": r_exports(), "python": python_exports(), "stata": stata_exports()}
    every = have["r"] | have["python"] | have["stata"]
    fn_notes = notes.get("functions", {})
    extra = notes.get("extra_rows", {})
    errors = []

    placed = {}
    for sec in notes["sections"]:
        for row in sec["rows"]:
            if row in placed:
                errors.append(f"`{row}` is listed in two sections ({placed[row]}, {sec['id']}).")
            placed[row] = sec["id"]
    for fn in sorted(every - set(placed)):
        langs = ", ".join(LANG_NAME[lg] for lg in LANGS if fn in have[lg])
        errors.append(f"`{fn}` is exported ({langs}) but has no row: add it to a section in "
                      f"book/_data/coverage.json.")
    for row in sorted(set(placed) - every - set(extra)):
        errors.append(f"row `{row}` names no exported function and is not an extra row: "
                      f"remove it, or add it under extra_rows.")
    for key in sorted(set(fn_notes) - every):
        errors.append(f"notes for `{key}`, which no language exports: remove them.")

    cells = {}
    for row in placed:
        if row in extra:
            e = extra[row]
            cells[row] = {"label": e["label"], **{lg: e[lg] for lg in LANGS}}
            continue
        n = fn_notes.get(row, {})
        cell = {"label": n.get("label", f"`{row}`")}
        for lg in LANGS:
            note = n.get(lg)
            if row in have[lg]:
                if note is not None and not note.startswith("Yes"):
                    errors.append(f"`{row}` exists in {LANG_NAME[lg]}, but its note says "
                                  f"\"{note}\": start the note with \"Yes\" or remove it.")
                cell[lg] = note or "Yes"
            else:
                if note is None:
                    errors.append(f"`{row}` is not in {LANG_NAME[lg]}: add a {lg} note saying "
                                  f"what to use instead (or n/a).")
                    note = "?"
                elif note.startswith("Yes"):
                    errors.append(f"`{row}` is not in {LANG_NAME[lg]}, but its note starts with "
                                  f"\"Yes\": fix the note.")
                cell[lg] = note
        cells[row] = cell
    return notes["sections"], cells, errors


def render_functions(sections, cells) -> dict:
    files = {}
    for sec in sections:
        lines = [HEADER, "| Function | R | Python | Stata |", "|---|---|---|---|"]
        for row in sec["rows"]:
            c = cells[row]
            lines.append("| " + " | ".join(md_escape(x) for x in
                                           (c["label"], c["r"], c["python"], c["stata"])) + " |")
        files[f"functions-{sec['id']}.md"] = "\n".join(lines) + "\n"
    return files


def render_badges(cells, extra_ids) -> dict:
    files = {}
    for row, c in sorted(cells.items()):
        if row in extra_ids:
            continue
        yes = [LANG_NAME[lg] for lg in LANGS if c[lg].startswith("Yes")]
        no = [f"{LANG_NAME[lg]}: {c[lg]}" for lg in LANGS if not c[lg].startswith("Yes")]
        text = "**Languages:** " + (", ".join(yes) if yes else "none")
        if no:
            text += ". " + "; ".join(no)
        text += ". See the [coverage matrix](../appendices/a-coverage-matrix.qmd).\n"
        files[f"badges/{row}.md"] = HEADER + "\n" + text
    return files


def render_api(keys: dict, notes: dict, errors: list) -> str:
    desc = notes.get("api_keys", {})
    for k in sorted(set(keys) - set(desc)):
        errors.append(f"api key `{k}` has no description: add it under api_keys in "
                      f"book/_data/coverage.json.")
    for k in sorted(set(desc) - set(keys)):
        errors.append(f"api_keys describes `{k}`, which neither language dispatches: remove it.")
    lines = [HEADER, "| `api =` | Source | R | Python | Default cache format |",
             "|---|---|---|---|---|"]
    for k, v in keys.items():
        if v["r_ext"] == v["python_ext"]:
            fmt = f"`.{v['r_ext']}`"
        else:
            fmt = f"`.{v['r_ext']}` (R) / `.{v['python_ext']}` (Python)"
        lines.append(f"| `\"{k}\"` | {md_escape(desc.get(k, '?'))} | "
                     f"{'Yes' if v['r'] else 'No'} | {'Yes' if v['python'] else 'No'} | {fmt} |")
    lines.append("")
    lines.append(f"{len(keys)} keys; Stata has no external-API wrapper and reads the cache with `dw_use`.")
    return "\n".join(lines) + "\n"


def render_rules(rules: dict) -> str:
    lines = [HEADER, "| Rule | Family | R | Python | What it flags |", "|---|---|---|---|---|"]
    order = sorted(rules, key=lambda r: (rules[r]["family"], r))
    for rid in order:
        v = rules[rid]
        if v["r"] and v["python"] and v["r"] != v["python"]:
            msg = f"R: {v['r']} Python: {v['python']}"
        else:
            msg = v["r"] or v["python"] or ""
        lines.append(f"| `{rid}` | {v['family']} | {'Yes' if v['r'] is not None else '—'} | "
                     f"{'Yes' if v['python'] is not None else '—'} | {md_escape(msg)} |")
    n_r = sum(1 for v in rules.values() if v["r"] is not None)
    n_py = sum(1 for v in rules.values() if v["python"] is not None)
    lines.append("")
    lines.append(f"R has {n_r} rules and Python {n_py}; ids are shared where the call is the same "
                 "in spirit, so a `# cso-allow:` directive reads the same in both.")
    return "\n".join(lines) + "\n"


def render_cases(cs: list) -> str:
    lines = [HEADER, "| Case | Kind | What it checks | R | Python | Stata |", "|---|---|---|---|---|---|"]
    n_check = n_gap = n_div = 0
    for c in cs:
        kind = c["kind"] + (", fixture" if c.get("reference") == "fixture" else "")
        cells = []
        for lg in LANGS:
            if lg in c.get("divergences", {}):
                cells.append(f"diverges ({c['divergences'][lg]['issue']})")
                n_div += 1
            elif lg in c.get("gaps", {}):
                cells.append("gap")
                n_gap += 1
            elif lg in c["languages"]:
                cells.append("checked")
                n_check += 1
            else:
                cells.append("?")
        lines.append(f"| `{c['id']}` | {kind} | {md_escape(c['title'])} | " + " | ".join(cells) + " |")
    lines.append("")
    lines.append(f"{len(cs)} cases: {n_check} language checks, {n_gap} gaps, {n_div} divergences. "
                 "A certificate records each check as a pass.")
    gaps = [(c["id"], lg, g) for c in cs for lg, g in c.get("gaps", {}).items()]
    if gaps:
        lines.append("")
        lines.append("Gaps:")
        lines.append("")
        for cid, lg, g in gaps:
            lines.append(f"- `{cid}`, {LANG_NAME[lg]}: {md_escape(g['reason'])} ({g['issue']})")
    return "\n".join(lines) + "\n"


def build() -> tuple:
    notes = json.loads(NOTES.read_text(encoding="utf-8"))
    sections, cells, errors = coverage(notes)
    files = {}
    if not errors:
        files.update(render_functions(sections, cells))
        files.update(render_badges(cells, set(notes.get("extra_rows", {}))))
    files["api-keys.md"] = render_api(api_keys(), notes, errors)
    files["audit-rules.md"] = render_rules(audit_rules())
    files["parity-cases.md"] = render_cases(cases())
    return files, errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="write nothing; fail if book/_generated/ is stale or the notes disagree")
    a = ap.parse_args()
    files, errors = build()
    if errors:
        print("[docs-tables] the coverage notes disagree with the code:")
        for e in errors:
            print("  - " + e)
        print("  Fix: edit book/_data/coverage.json, then run `sh tools/docs-tables`.")
        return 1
    on_disk = {p.relative_to(OUT).as_posix(): p for p in OUT.rglob("*.md")} if OUT.exists() else {}
    stale = sorted(k for k, v in files.items()
                   if k not in on_disk or on_disk[k].read_text(encoding="utf-8") != v)
    extra = sorted(set(on_disk) - set(files))
    if a.check:
        if stale or extra:
            print("[docs-tables] book/_generated/ is stale:")
            for k in stale:
                print(f"  - {k} (out of date or missing)")
            for k in extra:
                print(f"  - {k} (no longer generated)")
            print("  Fix: run `sh tools/docs-tables` and commit book/_generated/.")
            return 1
        print(f"[docs-tables] PASS: {len(files)} generated files are current.")
        return 0
    for k, v in files.items():
        p = OUT / k
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(v, encoding="utf-8", newline="\n")
    for k in extra:
        on_disk[k].unlink()
    print(f"[docs-tables] wrote {len(files)} files ({len(stale)} changed, {len(extra)} removed) "
          f"in book/_generated/.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
